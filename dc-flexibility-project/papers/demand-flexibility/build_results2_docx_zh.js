const LINE = { style: BorderStyle.SINGLE, size: 6, color: '000000' };
const NONE = { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' };
function table(widths, rows, caption, note) {
  const total = widths.reduce((a, b) => a + b, 0);
  const t = new Table({ width: { size: total, type: WidthType.DXA }, columnWidths: widths,
    rows: rows.map((row, i) => new TableRow({ tableHeader: i === 0, cantSplit: true,
      children: row.map((text, j) => new TableCell({ width: { size: widths[j], type: WidthType.DXA },
        margins: { top: 40, bottom: 40, left: 70, right: 70 },
        borders: { top: i === 0 ? LINE : NONE, bottom: i === 0 || i === rows.length - 1 ? LINE : NONE, left: NONE, right: NONE },
        children: [new Paragraph({ alignment: j === 0 ? AlignmentType.LEFT : AlignmentType.CENTER, spacing: { line: 260 },
          children: runs(String(text), { size: 18, font: i === 0 ? HEI : SONG }) })] })) })) });
  return [P(caption, { noIndent: true, size: 21, before: 160, keepNext: true, align: AlignmentType.LEFT }), t,
    ...(note ? [P(note, { noIndent: true, size: 18, color: '404040', line: 300, before: 60 })] : [])];
}

